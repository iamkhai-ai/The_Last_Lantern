/**
 * English-localization inventory: every player-visible Vietnamese string in `src/`.
 *
 * Run with:  node scripts/i18n-inventory.mjs [--markdown docs/i18n/inventory.md]
 *
 * It parses the TypeScript sources with the compiler API (no regex guessing) and reports every
 * string literal, template literal and JSX-free text chunk that contains Vietnamese letters. Comments
 * and type-only nodes are skipped, so the list is what the player can actually see.
 *
 * This is an authoring aid for the translation catalogue, not a runtime check. `check-i18n.mjs`
 * owns the pass/fail gate once the catalogue exists.
 */
import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const rootDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(rootDir, 'src');

/** Vietnamese-specific letters (and the Latin ones only Vietnamese words use in this project). */
const VIETNAMESE = /[ăâđêôơưàáảãạằắẳẵặầấẩẫậèéẻẽẹềếểễệìíỉĩịòóỏõọồốổỗộờớởỡợùúủũụừứửữựỳýỷỹỵ]/i;

function walk(dir, out = []) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    const stat = statSync(full);
    if (stat.isDirectory()) walk(full, out);
    else if (entry.endsWith('.ts')) out.push(full);
  }
  return out;
}

const files = walk(SRC).sort();
const rows = [];
const skipped = [];

for (const file of files) {
  const source = readFileSync(file, 'utf8');
  const ast = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true);
  const rel = relative(rootDir, file).replaceAll('\\', '/');

  const visit = (node) => {
    // Comments are not nodes we walk; JSDoc comments never reach here either.
    if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) {
      const text = node.text;
      if (VIETNAMESE.test(text)) {
        const { line } = ast.getLineAndCharacterOfPosition(node.getStart(ast));
        rows.push({ file: rel, line: line + 1, text });
      }
    } else if (ts.isTemplateExpression(node)) {
      // Keep the literal holes so translators can see the shape: "Màn {n} · {name}".
      let text = node.head.text;
      for (const span of node.templateSpans) text += `{…}${span.literal.text}`;
      if (VIETNAMESE.test(text)) {
        const { line } = ast.getLineAndCharacterOfPosition(node.getStart(ast));
        rows.push({ file: rel, line: line + 1, text: text.replaceAll('{…}', '{…}') });
      }
    }
    node.forEachChild(visit);
  };
  visit(ast);
}

const byFile = new Map();
for (const row of rows) {
  if (!byFile.has(row.file)) byFile.set(row.file, []);
  byFile.get(row.file).push(row);
}

const unique = new Map();
for (const row of rows) {
  if (!unique.has(row.text)) unique.set(row.text, []);
  unique.get(row.text).push(`${row.file}:${row.line}`);
}

const escapeCell = (value) => value.replaceAll('|', '\\|').replaceAll('\n', '⏎');
const markdown = [
  '# Player-visible Vietnamese strings — inventory',
  '',
  `Generated by \`node scripts/i18n-inventory.mjs\` from \`${relative(rootDir, SRC)}\`.`,
  '',
  `- string sites: **${rows.length}**`,
  `- unique strings: **${unique.size}**`,
  `- files with Vietnamese text: **${byFile.size}** of ${files.length} scanned`,
  '',
  '## Files',
  '',
  '| File | Sites |',
  '| --- | ---: |',
  ...[...byFile.entries()].sort((a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0])).map(([file, list]) => `| \`${file}\` | ${list.length} |`),
  '',
  '## Unique strings',
  '',
  '| # | String | Sites |',
  '| ---: | --- | --- |',
  ...[...unique.entries()].sort((a, b) => a[0].localeCompare(b[0], 'vi')).map(([text, where], index) => `| ${index + 1} | ${escapeCell(text)} | ${where.join('<br>')} |`),
  '',
].join('\n');

const markdownFlag = process.argv.indexOf('--markdown');
if (markdownFlag >= 0) {
  const target = process.argv[markdownFlag + 1];
  const out = join(rootDir, target);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, markdown, 'utf8');
  console.log(`wrote ${target}`);
}

console.log(`files scanned: ${files.length}`);
console.log(`files with Vietnamese text: ${byFile.size}`);
console.log(`string sites: ${rows.length}`);
console.log(`unique strings: ${unique.size}`);
console.log('');
for (const [file, list] of [...byFile.entries()].sort((a, b) => b[1].length - a[1].length)) {
  console.log(String(list.length).padStart(4), file);
}
if (skipped.length) console.log(`\nskipped: ${skipped.join(', ')}`);
